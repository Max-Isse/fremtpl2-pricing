"""Write the Phase 1 outputs: reports/data_quality.md, reports/exposure_analysis.md, CSVs and figures.

These Markdown files are generated; do not edit them by hand. Narrative docs link to them.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from fremtpl2_pricing import plotting
from fremtpl2_pricing.analysis.exposure import MODELS, ExposureResults
from fremtpl2_pricing.config import Config
from fremtpl2_pricing.data.quality import QualityReport

GENERATED = "<!-- GENERATED by `fremtpl2 report` - do not edit by hand. -->"
MODEL_LABELS = {"offset": "log(exposure) offset", "ignored": "exposure ignored", "feature": "log(exposure) as feature"}


def md(df: pd.DataFrame, floatfmt: str = ",.4g") -> str:
    return str(df.to_markdown(index=False, floatfmt=floatfmt, intfmt=","))


def _write_tables(tables: dict[str, pd.DataFrame], tables_dir: Path) -> None:
    tables_dir.mkdir(parents=True, exist_ok=True)
    for name, df in tables.items():
        df.to_csv(tables_dir / f"{name}.csv", index=False, float_format="%.10g")  # stable across parallel sums


def write_quality_report(rep: QualityReport, cfg: Config) -> Path:
    tables = {
        "lineage": rep.lineage,
        "cleaning_impact": rep.impact,
        "totals": rep.totals,
        "reconciliation_summary": rep.reconciliation,
        "reconciliation_by_idpol_decile": rep.reconciliation_decile,
        "duplicate_group_sizes": rep.duplicates["size_distribution"],
        "duplicate_group_nature": rep.duplicates["nature"],
        "large_loss_summary": rep.large_loss,
        "large_loss_sensitivity": rep.large_loss_sensitivity,
        "split_summary": rep.split_summary,
    }
    _write_tables(tables, cfg.path("tables_dir"))
    straddle = int(rep.duplicates["straddle"]["groups_straddling_split"].iloc[0])
    text = f"""{GENERATED}
# Data quality and lineage report

Generated {date.today().isoformat()} from `configs/config.yaml` (seed {cfg.seed}). CSV copies of every
table are in `reports/tables/`. Decisions referenced as D-xxx are explained in `docs/decisions.md`.

## 1. Lineage (row counts per table)

{md(rep.lineage)}

## 2. Totals before and after cleaning

{md(rep.totals, ",.2f")}

## 3. Impact of each cleaning decision

Changes are relative to the previous step's totals (negative = removed).

{md(rep.impact, ",.2f")}

## 4. Claim-count reconciliation (ClaimNb vs claim-amount records)

{md(rep.reconciliation, ",.2f")}

Where the missing amounts sit, by IDpol decile:

{md(rep.reconciliation_decile, ",.0f")}

## 5. Near-duplicate policies (identical rating factors)

{md(rep.duplicates["size_distribution"])}

What the duplicate groups look like:

{md(rep.duplicates["nature"], ",.3f")}

Groups straddling the train/holdout split after grouping: **{straddle}**.

## 6. Large losses

Cap estimated on training claims only (D-005):

{md(rep.large_loss, ",.4f")}

Sensitivity to the cap quantile (training claims):

{md(rep.large_loss_sensitivity, ",.4f")}

## 7. Split (grouped holdout + {cfg.section("split")["n_folds"]}-fold CV on the remainder)

{md(rep.split_summary, ",.4f")}
"""
    out = cfg.path("reports_dir") / "data_quality.md"
    out.write_text(text, encoding="utf-8")
    return out


def _figures(res: ExposureResults, fig_dir: Path) -> dict[str, Path]:
    figs: dict[str, Path] = {}

    fig, (ax,) = plotting.new_figure()
    h = res.exposure_hist
    ax.bar(h["lo"], h["policies"], width=(h["hi"] - h["lo"]) * 0.9, align="edge", color=plotting.SERIES[0])
    ax.set_title("Exposure per record (training split)")
    ax.set_xlabel("Exposure (years on cover, capped at 1)")
    ax.set_ylabel("Policies")
    figs["exposure_hist"] = plotting.save(fig, fig_dir / "exposure_hist.png")

    fig, axes = plotting.new_figure(width=9, ncols=2)
    b = res.band_summary
    x = np.arange(len(b))
    axes[0].bar(x, b["claims_per_policy"], color=plotting.SERIES[0], width=0.6)
    axes[0].set_title("Claims per record")
    axes[1].bar(x, b["claims_per_year"], color=plotting.SERIES[0], width=0.6)
    axes[1].set_title("Claims per exposure-year (annualised)")
    for ax in axes:
        ax.set_xticks(x, b["exposure_band"], rotation=30, ha="right")
        ax.set_xlabel("Exposure band (years)")
    figs["frequency_by_exposure_band"] = plotting.save(fig, fig_dir / "frequency_by_exposure_band.png")

    fig, (ax,) = plotting.new_figure(width=8)
    ae = res.ae_by_band[res.ae_by_band["exposure_band"] != "total"]
    x = np.arange(len(ae))
    w = 0.26
    for i, m in enumerate(MODELS):
        ax.bar(x + (i - 1) * w, ae[f"ae_{m}"], width=w - 0.02, color=plotting.SERIES[i], label=MODEL_LABELS[m])
    ax.axhline(1.0, color=plotting.REFERENCE, linewidth=1, linestyle="--")
    ax.set_xticks(x, ae["exposure_band"], rotation=30, ha="right")
    ax.set_xlabel("Exposure band (years)")
    ax.set_ylabel("Actual / expected claims")
    ax.set_title("Out-of-fold actual/expected by exposure band", pad=28)
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.0), ncols=3)
    figs["ae_by_exposure_band"] = plotting.save(fig, fig_dir / "ae_by_exposure_band.png")

    fig, (ax,) = plotting.new_figure(width=8)
    for i, m in enumerate(MODELS):
        r = res.relativities[res.relativities["model"] == m]
        ax.plot(
            r["DrivAge_band"],
            r["relativity"],
            marker="o",
            markersize=5,
            color=plotting.SERIES[i],
            label=MODEL_LABELS[m],
        )
    ax.axhline(1.0, color=plotting.REFERENCE, linewidth=1, linestyle="--")
    ax.set_xlabel("Driver age band")
    ax.set_ylabel("Relativity vs youngest band")
    ax.set_title("Driver-age relativities depend on how exposure enters")
    ax.tick_params(axis="x", rotation=30)
    ax.legend()
    figs["drivage_relativities"] = plotting.save(fig, fig_dir / "drivage_relativities.png")
    return figs


def write_exposure_report(res: ExposureResults, cfg: Config) -> Path:
    tables = {
        "exposure_band_summary": res.band_summary,
        "exposure_ae_by_band": res.ae_by_band,
        "exposure_log_coef": res.log_exposure_coef,
        "exposure_drivage_relativities": res.relativities,
        "exposure_annual_frequency": res.annual_frequency,
        "exposure_model_deviance": res.deviance,
    }
    _write_tables(tables, cfg.path("tables_dir"))
    figs = _figures(res, cfg.path("figures_dir"))
    rel_wide = res.relativities.pivot_table(
        index="DrivAge_band", columns="model", values="relativity", sort=False
    ).reset_index()
    exposure_cols = res.relativities.drop_duplicates("DrivAge_band")[["DrivAge_band", "policies", "mean_exposure"]]
    rel_wide = rel_wide.merge(exposure_cols, on="DrivAge_band")
    factors = ", ".join(cfg.section("exposure_analysis")["demo_factors"])
    rel = lambda p: Path("figures") / p.name  # noqa: E731 - relative link from reports/
    text = f"""{GENERATED}
# Exposure analysis

Training split only. Models are Poisson GLMs on the same factors ({factors}), fitted on folds 1-4 and
evaluated on fold 0. The holdout is not used. See `docs/methodology.md` section 1 for the interpretation.

## Claim counts scale with time at risk

![exposure histogram]({rel(figs["exposure_hist"]).as_posix()})

{md(res.band_summary, ",.4f")}

![frequency by exposure band]({rel(figs["frequency_by_exposure_band"]).as_posix()})

## Offset vs ignored vs free coefficient

Coefficient on log(exposure) when it is a free regressor (1 = proportional to time on cover):

{md(res.log_exposure_coef, ",.4f")}

Out-of-fold actual/expected by exposure band (fold 0):

{md(res.ae_by_band, ",.3f")}

![A/E by exposure band]({rel(figs["ae_by_exposure_band"]).as_posix()})

Annual claim frequency each model implies for a full policy year, averaged over fold 0 policies:

{md(res.annual_frequency, ",.4f")}

Driver-age relativities and mean exposure per band (training folds 1-4):

{md(rel_wide, ",.3f")}

![driver-age relativities]({rel(figs["drivage_relativities"]).as_posix()})

Out-of-fold Poisson deviance (lower is better; not comparable to pricing usefulness, see methodology):

{md(res.deviance, ",.1f")}
"""
    out = cfg.path("reports_dir") / "exposure_analysis.md"
    out.write_text(text, encoding="utf-8")
    return out
